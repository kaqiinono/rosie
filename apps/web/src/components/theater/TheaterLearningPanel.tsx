'use client'

import { useEffect, useId, useMemo, useRef, useState } from 'react'
import { supabase, type WordEntry } from '@rosie/core'
import { WordPopup } from '@rosie/english'
import { Star, StickerCard } from '@rosie/ui'
import { Button, Flex, IconButton, Spinner, Text } from '@rosie/ui/themes'
import { theaterTime } from '@/lib/theater/subtitle-timeline'
import type { TheaterCue, TheaterStudyItem } from '@/lib/theater/types'

type Lookup = { cueId: string; word: string; headwordId: string | null; entry?: WordEntry }
type LearningItem = TheaterStudyItem & { kind: 'favorite' | 'word' }
type CueSurface = 'list' | 'current'
type CueTextOptions = { surface?: CueSurface; highlighted?: boolean; showTranslation?: boolean }
type Props = {
  userId: string
  filmId: string
  onPause: () => void
  onReview: (item: TheaterStudyItem) => void
}

const wordPattern = /([\p{Script=Latin}\p{M}]+(?:['’\-][\p{Script=Latin}\p{M}]+)*)/u
const wordButtonClass = 'm-0! inline! h-auto! min-h-0! min-w-0! p-0! align-baseline [font:inherit]! [color:inherit]! hover:underline focus-visible:underline'
const subtitleNoticePattern = /^(?:(?:this subtitle (?:is|was)|(?:these )?subtitles (?:are|were)) automatically generated by ai|[此本]字幕(?:由|为)\s*ai\s*自动生成)[.!。！]?$/i
const fields = 'kind,item_key,position_ms,cue_text,detail,headword_id'
const itemIdentity = (item: TheaterStudyItem) => item.kind + ':' + item.item_key
const itemLabels = { favorite: '收藏', word: '生词' }
const cueSnapshot = (cue: TheaterCue) => [cue.en, cue.zh].filter(Boolean).join('\n').slice(0, 4000)

function favoriteKey(cue: TheaterCue) {
  const text = cue.en ?? cue.zh ?? ''
  let hash = 2166136261
  for (let index = 0; index < text.length; index++) hash = Math.imul(hash ^ text.charCodeAt(index), 16777619)
  return 'saved-' + (cue.en ? 'en' : 'zh') + '-' + cue.startMs + '-' + cue.endMs + '-' + (hash >>> 0).toString(36)
}

export function savedTheaterCueEnd(item: TheaterStudyItem) {
  if (item.kind !== 'favorite') return undefined
  const match = /^(?:saved-)?(?:en|zh)-(\d+)-(\d+)-[0-9a-z]+$/.exec(item.item_key)
  const end = Number(match?.[2])
  return Number(match?.[1]) === item.position_ms && end > item.position_ms ? end : undefined
}

export function matchesTheaterStudyCue(item: TheaterStudyItem, cue: TheaterCue) {
  if (item.position_ms !== cue.startMs) return false
  if (item.kind === 'word') return item.cue_text === cueSnapshot(cue)
  if (item.item_key.startsWith('saved-')) return item.item_key === favoriteKey(cue)
  return savedTheaterCueEnd(item) === cue.endMs && item.cue_text === cueSnapshot(cue)
}

export function isTheaterSubtitleNotice(cue: TheaterCue) {
  const lines = [cue.en, cue.zh].filter((line): line is string => Boolean(line?.trim()))
  return lines.length > 0 && lines.every(line => subtitleNoticePattern.test(line.normalize('NFKC').trim().replace(/\s+/g, ' ')))
}

export function useTheaterLearning({ userId, filmId, onPause, onReview }: Props) {
  const recordsId = useId()
  const [recordsOpen, setRecordsOpen] = useState(false)
  const [items, setItems] = useState<LearningItem[] | null>(null)
  const [lookupTarget, setLookupTarget] = useState<{ cue: TheaterCue; surface: CueSurface; wordIndex: number } | null>(null)
  const lookupCue = lookupTarget?.cue
  const [lookupResult, setLookup] = useState<Lookup | null>(null)
  const lookup = lookupResult?.cueId === lookupCue?.id ? lookupResult : null
  const [pending, setPending] = useState<'read' | 'lookup' | 'write' | null>(null)
  const [error, setError] = useState('')
  const [notice, setNotice] = useState('')
  const [limit, setLimit] = useState(20)
  const activeRequest = useRef<AbortController | null>(null)
  const favorites = useMemo(() => {
    const byPosition = new Map<number, LearningItem[]>()
    for (const item of items ?? []) {
      if (item.kind !== 'favorite') continue
      const entries = byPosition.get(item.position_ms)
      if (entries) entries.push(item)
      else byPosition.set(item.position_ms, [item])
    }
    return byPosition
  }, [items])

  async function run(operation: NonNullable<typeof pending>, work: (signal: AbortSignal) => Promise<void>) {
    if (activeRequest.current) return
    const controller = new AbortController()
    activeRequest.current = controller
    setPending(operation)
    setError('')
    setNotice('')
    try {
      const { data } = await supabase.auth.getSession()
      if (controller.signal.aborted) return
      if (data.session?.user.id !== userId) throw Error('请重新登录。')
      await work(controller.signal)
    } catch (cause) {
      if (!controller.signal.aborted)
        setError(cause instanceof Error ? cause.message : '操作未完成，请重试。')
    } finally {
      if (activeRequest.current === controller) {
        activeRequest.current = null
        setPending(null)
      }
    }
  }

  function load() {
    void run('read', async signal => {
      const { data, error } = await supabase.from('theater_study_items').select(fields)
        .eq('user_id', userId).eq('film_id', filmId).in('kind', ['favorite', 'word'])
        .order('created_at', { ascending: false })
        .abortSignal(signal)
      if (signal.aborted) return
      if (error) throw Error('暂时无法读取学习记录。')
      setItems(data as LearningItem[])
    })
  }

  useEffect(() => {
    load()
    return () => {
      activeRequest.current?.abort()
      activeRequest.current = null
    }
    // This component is keyed by its owner and film.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  function lookupWord(cue: TheaterCue, word: string, surface: CueSurface, wordIndex: number) {
    const cueId = cue.id
    onPause()
    setLookupTarget({ cue, surface, wordIndex })
    setLookup(null)
    void run('lookup', async signal => {
      const { data: headwordId, error } = await supabase.rpc('find_vocabulary_headword', { p_word: word })
        .abortSignal(signal)
      if (signal.aborted) return
      if (error) throw Error('暂时无法查词，请重试。')
      if (typeof headwordId !== 'string') { setLookup({ cueId, word, headwordId: null }); return }
      const result = await supabase.from('vocabulary_search').select('id,word,stage,unit,lesson,ipa,example,shared_explanation,shared_chinese_def')
        .eq('headword_id', headwordId).abortSignal(signal).maybeSingle()
      if (signal.aborted) return
      if (result.error) throw Error('暂时无法读取词义，请重试。')
      const row = result.data
      setLookup({
        cueId, word, headwordId,
        entry: row ? {
          id: row.id, headwordId, word: row.word, stage: row.stage ?? undefined,
          unit: row.unit, lesson: row.lesson, ipa: row.ipa?.trim() || undefined,
          example: row.example ?? undefined, explanation: row.shared_explanation ?? '',
          chineseDef: row.shared_chinese_def ?? undefined,
        } : undefined,
      })
    })
  }

  function storeItem(item: LearningItem, remove = false) {
    void run('write', async signal => {
      const table = supabase.from('theater_study_items')
      const result = await (remove
        ? table.delete().eq('user_id', userId).eq('film_id', filmId).eq('kind', item.kind).eq('item_key', item.item_key)
        : table.upsert({ ...item, user_id: userId, film_id: filmId }, { onConflict: 'user_id,film_id,kind,item_key' }))
        .abortSignal(signal)
      if (signal.aborted) return
      if (result.error) throw Error('学习记录未保存，请重试。')
      setItems(current => {
        const rest = (current ?? []).filter(existing => itemIdentity(existing) !== itemIdentity(item))
        return remove ? rest : [item, ...rest]
      })
      setNotice(remove ? '已移除' + itemLabels[item.kind] : '已保存' + itemLabels[item.kind])
    })
  }

  function cueItem(cue: TheaterCue, kind: LearningItem['kind'], word?: Lookup): LearningItem {
    return {
      kind, item_key: word ? word.word.toLowerCase() : favoriteKey(cue), position_ms: cue.startMs,
      cue_text: cueSnapshot(cue), detail: word?.word ?? '',
      headword_id: word?.headwordId ?? null,
    }
  }

  function favoriteButton(cue: TheaterCue) {
    if (isTheaterSubtitleNotice(cue)) return null
    const favorite = favorites.get(cue.startMs)?.find(item => matchesTheaterStudyCue(item, cue))
    return (
      <IconButton type="button" size="1" variant={favorite ? 'soft' : 'ghost'}
        aria-label={'收藏 ' + theaterTime(cue.startMs) + ' 的台词'} aria-pressed={Boolean(favorite)}
        title={favorite ? '取消收藏' : '收藏此句'} disabled={pending !== null || items === null}
        onClick={() => {
          onPause()
          storeItem(favorite ?? cueItem(cue, 'favorite'), Boolean(favorite))
        }}>
        <Star size={15} fill={favorite ? 'currentColor' : 'none'} aria-hidden="true" />
      </IconButton>
    )
  }

  const lookupItem = lookupCue && lookup ? cueItem(lookupCue, 'word', lookup) : null
  const lookupSaved = lookupItem && items?.some(item => itemIdentity(item) === itemIdentity(lookupItem))
  const saveWord = lookupItem && (
    <Button type="button" variant="soft" disabled={pending !== null || items === null || !!lookupSaved}
      onClick={() => storeItem(lookupItem)}>{lookupSaved ? '已存入生词' : '存入生词'}</Button>
  )

  const feedback = <>
    {error && <Text role="alert" color="red" size="2">{error}</Text>}
    {notice && <Text role="status" size="2">{notice}</Text>}
    {pending === 'read' && <Text role="status" size="2"><Spinner /> 正在读取学习记录…</Text>}
    {items === null && pending === null && <Button onClick={load} variant="soft">重新读取记录</Button>}
  </>
  const cueText = (cue: TheaterCue, { surface = 'list', highlighted, showTranslation }: CueTextOptions = {}) => {
    if (isTheaterSubtitleNotice(cue)) return (
      <Text as="div" size="2" color="gray">
        {surface === 'current' ? cue.en ?? cue.zh : [cue.en, cue.zh].filter(Boolean).join('\n')}
      </Text>
    )
    const context = surface === 'current' && !highlighted
    const selectedWordIndex = lookupTarget?.cue.id === cue.id && lookupTarget.surface === surface &&
      (lookup || pending === 'lookup') ? lookupTarget.wordIndex : -1
    return <>
      {cue.en && <Text as="div" size={surface === 'list' ? '3' : highlighted ? '5' : '2'}
        weight={highlighted ? 'bold' : context ? 'regular' : 'medium'}
        className={surface === 'list' ? 'leading-[1.35] text-[var(--gray-12)]!'
          : context ? 'leading-[1.4] text-text-secondary' : 'leading-[1.4] text-text-primary'}>
        {cue.en.split(wordPattern).map((part, index) => index % 2 === 1 && part.length <= 120 ? (
          <Button key={index} type="button" variant="ghost" disabled={pending !== null}
            className={index === selectedWordIndex ? wordButtonClass + ' underline underline-offset-2' : wordButtonClass}
            onClick={() => lookupWord(cue, part, surface, index)} aria-label={'查询 ' + part}>{part}</Button>
        ) : <span key={index}>{part}</span>)}
      </Text>}
      {cue.zh && (surface === 'list' || !cue.en || showTranslation) &&
        <Text as="div" size={highlighted ? (cue.en ? '3' : '5') : '2'}
          color={surface === 'list' || cue.en || context ? 'gray' : undefined}
          weight={highlighted && !cue.en ? 'bold' : undefined}
          className={surface === 'list' ? 'leading-tight' : undefined}>{cue.zh}</Text>}
    </>
  }
  const cueDetails = (cue: TheaterCue, surface: CueSurface = 'list') =>
    cue.id === lookupTarget?.cue.id && surface === lookupTarget.surface && (lookup || pending === 'lookup') && (
      <Flex direction="column" gap="2" className="border-kid-line mt-2 border-t pt-2">
        {pending === 'lookup' && <Text role="status" size="2"><Spinner /> 正在查词…</Text>}
        {lookup?.entry && <WordPopup entry={lookup.entry} mastery={undefined} showMastery={false}
          sourceContext={cue.en ? { title: '影片台词', sentence: cue.en, matchedForm: lookup.word } : undefined}
          onClose={() => setLookup(null)}
          actions={<Flex direction="column" gap="2" align="start">
            {error && <Text role="alert" color="red" size="2">{error}</Text>}
            {saveWord}
          </Flex>} />}
        {lookup && !lookup.entry && <StickerCard size="sm" tone="paper" elevation="flat">
          <Flex direction="column" gap="2">
            <Text weight="bold">{lookup.word}</Text>
            <Text size="2" color="gray">共享词库暂未收录这个词的释义。</Text>
            <Flex gap="2" wrap="wrap">
              {saveWord}
              <Button type="button" variant="ghost" onClick={() => setLookup(null)}>关闭释义</Button>
            </Flex>
          </Flex>
        </StickerCard>}
      </Flex>
    )
  const recordsButton = (
    <Button type="button" size="1" variant="soft" aria-expanded={recordsOpen} aria-controls={recordsId}
      onClick={() => setRecordsOpen(open => !open)}>本片学习记录</Button>
  )
  const records = (
    <div id={recordsId} hidden={!recordsOpen}>
      {recordsOpen && <Flex direction="column" gap="2" className="max-h-64 overflow-y-auto p-0.5">
        {items?.length === 0 && <Text size="2" color="gray">还没有学习记录。</Text>}
        {items?.slice(0, limit).map(item => (
          <StickerCard key={itemIdentity(item)} size="sm" elevation="flat" tone="paper">
            <Flex direction="column" gap="2">
              <Text size="2" weight="bold">{itemLabels[item.kind]} · {theaterTime(item.position_ms)}</Text>
              <Text size="2" className="whitespace-pre-wrap break-words">{item.cue_text}</Text>
              {item.detail && <Text size="2" className="whitespace-pre-wrap break-words">{item.detail}</Text>}
              <Flex gap="2" wrap="wrap">
                <Button type="button" variant="soft" onClick={() => {
                  setLookup(null)
                  setRecordsOpen(false)
                  onReview(item)
                }}>回看原片</Button>
                <Button type="button" variant="ghost" disabled={pending !== null}
                  onClick={() => storeItem(item, true)}>移除{itemLabels[item.kind]}</Button>
              </Flex>
            </Flex>
          </StickerCard>
        ))}
        {items && items.length > limit && <Button variant="soft" onClick={() => setLimit(value => value + 20)}>显示更多</Button>}
      </Flex>}
    </div>
  )
  return { recordsButton, records, feedback, cueText, cueDetails, favoriteButton }
}
