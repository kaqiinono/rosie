export const LESSON_TIP =
  '先找物品和分配对象，再写两种方案；分配对象数=总差÷单位差，最后代回求物品数。'

export const LESSON_SUMMARY = [
  '盈亏问题的本质：把同一批东西分给同一批对象，比较两种分配方案。',
  '三个不变量：物品总数不变；分配对象及其数量不变；同一种方案内，每个对象分得的数量相同。两种方案之间，每个对象分得的数量可以不同。',
  '① 找到把什么分给什么，确定物品和分配对象。人、桌、船、房间、天、馒头都可能是分配对象。',
  '② 写出两种分配方案：每个对象分多少，最后盈多少或亏多少。这步最难：先统一对象数、统一物品单位，再把提前、延后、空桌、没领到、部分加量等条件转化。',
  '③ 分配对象数=总差÷单位差。单位差是两种方案每个对象分配量的差；总差：盈盈用大盈−小盈，亏亏用大亏−小亏，盈亏用盈+亏。恰好分完时盈亏记0。',
  '④ 用其中一种方案求物品数：每份数量×对象数+盈，或每份数量×对象数−亏。最后用另一种方案验算，按问题要求换算单位。',
  '基础示例：每人5块余20块，每人8块余2块。人数=(20−2)÷(8−5)=6人，物品数=5×6+20=50块。',
  '恰好分完：每包6颗余28颗，每包10颗刚好分完。包数=(28−0)÷(10−6)=7包，物品数=7×10=70颗。',
  '盈亏示例：每房4人还剩10人，每房6人缺8人。房间数=(10+8)÷(6−4)=9间，人数=4×9+10=46人。',
  '亏亏示例：每天10个缺20个，每天13个缺35个。天数=(35−20)÷(13−10)=5天，物品数=5×10−20=30个。',
]

